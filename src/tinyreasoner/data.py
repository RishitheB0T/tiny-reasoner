"""
Synthetic reasoning tasks with step-by-step working ("chain of thought").

Every problem is generated by code, so we always know the right answer.
That is what makes the reward in GRPO "verifiable": a Python function can
check the model's answer, no human labels needed.

One problem looks like this (the model sees the prompt, and must write the
completion itself, digit by digit, right-to-left like school maths):

    prompt:      Q:347+586\nA:
    completion:  347+586:7+6+0=13|4+8+1=13|3+5+1=9|=933;<answer>933</answer>

Each "sub-calculation" is   <a><op><b>:<step>|<step>|...|=<result>;
and a problem is one or more sub-calculations followed by <answer>...</answer>.

Run as a script to write all datasets to data/:
    python -m tinyreasoner.data --out data
"""

import argparse
import json
import os
import random
import re

# -----------------------------------------------------------------------------
# step-by-step "working" for each operation


def _digits(n):
    """digits of n, least significant first: 347 -> [7, 4, 3]"""
    return [int(c) for c in str(n)][::-1]


def add_steps(a, b):
    """7+6+0=13 means: digit of a + digit of b + carry-in = column sum"""
    da, db = _digits(a), _digits(b)
    steps, carry = [], 0
    for i in range(max(len(da), len(db))):
        x = da[i] if i < len(da) else 0
        y = db[i] if i < len(db) else 0
        s = x + y + carry
        steps.append(f"{x}+{y}+{carry}={s}")
        carry = s // 10
    return steps, a + b


def sub_steps(a, b):
    """5-7-0=8b1 means: 5 - 7 - borrow-in(0) -> write 8, borrow 1 from next column"""
    assert a >= b
    da, db = _digits(a), _digits(b)
    steps, borrow = [], 0
    for i in range(len(da)):
        x = da[i]
        y = db[i] if i < len(db) else 0
        d = x - y - borrow
        nb = 1 if d < 0 else 0
        d += 10 * nb
        steps.append(f"{x}-{y}-{borrow}={d}b{nb}")
        borrow = nb
    return steps, a - b


def mul1_steps(a, m):
    """multiply by a single digit m. 7*6+0=42 means: digit*m + carry-in = value"""
    assert 0 <= m <= 9
    steps, carry = [], 0
    for x in _digits(a):
        v = x * m + carry
        steps.append(f"{x}*{m}+{carry}={v}")
        carry = v // 10
    return steps, a * m


def div1_steps(a, m):
    """long division by a single digit m, left to right. 14/4=3r2 means 14 = 4*3 + 2"""
    assert 2 <= m <= 9
    steps, r = [], 0
    for c in str(a):
        cur = r * 10 + int(c)
        q, r = divmod(cur, m)
        steps.append(f"{cur}/{m}={q}r{r}")
    return steps, f"{a // m}r{a % m}"


def subcalc(a, op, b, steps, result):
    return f"{a}{op}{b}:" + "|".join(steps) + f"|={result};"


# -----------------------------------------------------------------------------
# problem kinds


def make_add(rng, nd):
    a, b = _num(rng, nd), _num(rng, nd)
    steps, r = add_steps(a, b)
    return f"{a}+{b}", subcalc(a, "+", b, steps, r), str(r)


def make_sub(rng, nd):
    a, b = _num(rng, nd), _num(rng, nd)
    a, b = max(a, b), min(a, b)
    steps, r = sub_steps(a, b)
    return f"{a}-{b}", subcalc(a, "-", b, steps, r), str(r)


def make_mul1(rng, nd):
    a, m = _num(rng, nd), rng.randint(2, 9)
    steps, r = mul1_steps(a, m)
    return f"{a}*{m}", subcalc(a, "*", m, steps, r), str(r)


def make_mul2(rng, nd_a, nd_b):
    """a * b with a multi-digit b: one single-digit multiply per digit of b, then add them up"""
    a = _num(rng, nd_a)
    b = int("".join(str(rng.randint(1, 9)) for _ in range(nd_b)))  # no zero digits in b
    parts, total = [], None
    for j, m in enumerate(_digits(b)):
        steps, p = mul1_steps(a, m)
        parts.append(subcalc(a, "*", m, steps, p))
        p *= 10 ** j  # shift by the digit's place value
        if total is None:
            total = p
        else:
            steps, s = add_steps(total, p)
            parts.append(subcalc(total, "+", p, steps, s))
            total = s
    assert total == a * b
    return f"{a}*{b}", "".join(parts), str(total)


def make_expr(rng, n_ops, nd):
    """a+b-c+...: evaluated left to right, one sub-calculation per operator"""
    nums = [_num(rng, nd) for _ in range(n_ops + 1)]
    ops = [rng.choice("+-") for _ in range(n_ops)]
    parts, cur = [], nums[0]
    for i, (op, b) in enumerate(zip(ops, nums[1:])):
        if op == "-" and b > cur:  # keep everything non-negative
            op = ops[i] = "+"
        steps, r = (add_steps if op == "+" else sub_steps)(cur, b)
        parts.append(subcalc(cur, op, b, steps, r))
        cur = r
    q = str(nums[0]) + "".join(o + str(n) for o, n in zip(ops, nums[1:]))
    assert eval(q) == cur
    return q, "".join(parts), str(cur)


def make_div(rng, nd):
    a, m = _num(rng, nd), rng.randint(2, 9)
    steps, r = div1_steps(a, m)
    return f"{a}/{m}", subcalc(a, "/", m, steps, r), r


def _num(rng, nd):
    """a random number with exactly nd digits"""
    return rng.randint(10 ** (nd - 1) if nd > 1 else 0, 10**nd - 1)


# difficulty levels: list of (kind, args). Level 5 is the "hard" level (rare in training).
# Level 6 is LONGER than anything in the training data (tests length generalization).
LEVELS = {
    1: [("add", (2,)), ("sub", (2,)), ("mul1", (2,))],
    2: [("add", (3,)), ("sub", (3,)), ("mul1", (3,))],
    3: [("add", (4,)), ("sub", (4,)), ("mul1", (4,)), ("expr", (2, 2))],
    4: [("add", (5,)), ("sub", (5,)), ("mul2", (2, 2)), ("expr", (3, 2))],
    5: [("add", (6,)), ("sub", (6,)), ("mul2", (3, 2)), ("expr", (3, 3))],
    6: [("add", (7,)), ("sub", (7,)), ("mul2", (4, 2)), ("expr", (4, 3))],
}
DIV_LEVELS = {1: [("div", (2,))], 2: [("div", (3,))], 3: [("div", (4,))], 4: [("div", (5,))]}
MAKERS = {"add": make_add, "sub": make_sub, "mul1": make_mul1, "mul2": make_mul2,
          "expr": make_expr, "div": make_div}


def make_prompt(question):
    return f"Q:{question}\nA:"


def make_problem(rng, level, levels=LEVELS):
    kind, args = rng.choice(levels[level])
    question, work, answer = MAKERS[kind](rng, *args)
    return {
        "question": question,
        "level": level,
        "kind": kind,
        "prompt": make_prompt(question),
        "completion": f"{work}<answer>{answer}</answer>",
        "answer": answer,
    }


def generate(n, level_weights, seed, levels=LEVELS, exclude=()):
    """n problems; level_weights is {level: weight}. Questions in `exclude` are skipped."""
    rng = random.Random(seed)
    lv, w = zip(*level_weights.items())
    exclude, out, seen = set(exclude), [], set()
    while len(out) < n:
        p = make_problem(rng, rng.choices(lv, w)[0], levels)
        if p["question"] in exclude or p["question"] in seen:
            continue
        seen.add(p["question"])
        out.append(p)
    return out


# -----------------------------------------------------------------------------
# checking answers (this is the "verifier" used for evaluation and RL rewards)

ANSWER_RE = re.compile(r"<answer>([0-9r\-]+)</answer>")


def extract_answer(completion):
    """the text inside the first <answer>...</answer>, or None"""
    m = ANSWER_RE.search(completion)
    return m.group(1) if m else None


def is_correct(completion, answer):
    return extract_answer(completion) == answer


# -----------------------------------------------------------------------------


def save_jsonl(rows, path):
    with open(path, "w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")


def load_jsonl(path):
    with open(path) as f:
        return [json.loads(line) for line in f]


def main():
    ap = argparse.ArgumentParser(description="generate all synthetic datasets")
    ap.add_argument("--out", default="data")
    ap.add_argument("--n_train", type=int, default=200_000)
    ap.add_argument("--n_test", type=int, default=300, help="per level")
    ap.add_argument("--n_rl", type=int, default=20_000)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    # test sets first, so that nothing in them leaks into training data
    tests = {lv: generate(args.n_test, {lv: 1}, seed=1000 + lv) for lv in LEVELS}
    div_test = generate(args.n_test, {1: 1, 2: 1, 3: 1, 4: 1}, seed=2000, levels=DIV_LEVELS)
    held_out = {p["question"] for t in tests.values() for p in t} | {p["question"] for p in div_test}

    # SFT data: mostly levels 1-4, only a sprinkle of the hard level 5,
    # so the model knows the format but is weak on long problems (room for RL)
    sft_weights = {1: 0.15, 2: 0.25, 3: 0.27, 4: 0.30, 5: 0.03}
    train = generate(args.n_train, sft_weights, seed=1, exclude=held_out)
    val = generate(2000, sft_weights, seed=2, exclude=held_out | {p["question"] for p in train})
    # RL prompts: the harder levels, including level 6 which SFT never saw
    rl = generate(args.n_rl, {3: 0.1, 4: 0.2, 5: 0.35, 6: 0.35}, seed=3, exclude=held_out)
    # a NEW task (long division) used later to show LoRA fine-tuning
    div_train = generate(30_000, {1: 1, 2: 1, 3: 1, 4: 1}, seed=4, levels=DIV_LEVELS, exclude=held_out)

    save_jsonl(train, f"{args.out}/train.jsonl")
    save_jsonl(val, f"{args.out}/val.jsonl")
    save_jsonl(rl, f"{args.out}/rl_prompts.jsonl")
    save_jsonl(div_train, f"{args.out}/div_train.jsonl")
    save_jsonl(div_test, f"{args.out}/div_test.jsonl")
    for lv, t in tests.items():
        save_jsonl(t, f"{args.out}/test_L{lv}.jsonl")
    print(f"train={len(train)} val={len(val)} rl={len(rl)} div_train={len(div_train)} "
          f"test={sum(len(t) for t in tests.values())} div_test={len(div_test)}")
    ex = train[0]
    print("example:\n" + ex["prompt"] + ex["completion"])


if __name__ == "__main__":
    main()
